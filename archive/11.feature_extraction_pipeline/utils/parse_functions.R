#' Parse District Number from Text
#'
#' @param text A character string containing state and district information.
#'
#' @details
#' This function attempts to extract a district number (or "0" if "at large") 
#' from a string of the format "StateName Nth" or "StateName at large".
#'
#' @return A character string representing the district number. Returns 
#' "Invalid format" if parsing fails.
#'
#' @examples
#' parse_district_number("California 12th")
#' # Returns "12"
#' parse_district_number("Alaska at large")
#' # Returns "0"
#'
#' @export
parse_district_number <- function(text) {
  if (!is.character(text) || length(text) != 1) {
    stop("`text` must be a single character string.")
  }
  
  match <- regexec("([A-Za-z\\s]+)\\s(\\d+(?:th|st|nd|rd)|at large)", text)
  matches <- regmatches(text, match)[[1]]
  
  if (length(matches) > 0) {
    district <- matches[3]
    if (district == "at large") {
      return("0")
    } else {
      return(gsub("[^0-9]", "", district))
    }
  } else {
    return("Invalid format")
  }
}
