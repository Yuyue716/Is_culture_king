#' Parse Features into a Data Table
#'
#' @param features A character vector, where each element represents a feature block.
#'
#' @details
#' This function takes a character vector, where each element is expected to have 
#' a header line and subsequent lines containing codes and descriptions. It parses 
#' this input into a list of data tables, with each data table corresponding to a 
#' feature block.
#'
#' @return A named list of data.tables, where the name corresponds to the header 
#' and each data.table has two columns: one for codes and one for descriptions.
#'
#' @examples
#' features <- c(
#'   "Feature1:\n(A1) Description A1\n(A2) Description A2",
#'   "Feature2:\n(B1) Description B1\n(B2) Description B2"
#' )
#' parsed <- parse_features(features)
#' parsed$Feature1
#' 
#' @export
parse_features <- function(features) {
  if (!is.character(features)) {
    stop("`features` must be a character vector.")
  }
  
  parsed_list <- list()
  
  for (feature in features) {
    # Split by newline to separate header and values
    lines <- unlist(strsplit(feature, "\n"))
    if (length(lines) < 2) {
      warning("A feature block does not contain any codes/descriptions:\n", feature)
      next
    }
    
    # Extract the header (first line) and remove trailing colon
    header <- gsub(":", "", lines[1])
    header <- trimws(header)
    if (nchar(header) == 0) {
      warning("A feature block has an empty header:\n", feature)
    }
    
    # Extract codes and descriptions from subsequent lines
    codes <- gsub("\\).*", "", lines[-1])      # Strip everything after ')'
    codes <- trimws(gsub("^\\(", "", codes))    # Remove leading '(' and trim
    descriptions <- gsub(".*\\)\\s*", "", lines[-1])
    descriptions <- trimws(descriptions)
    
    # Remove empty entries if any
    valid_idx <- codes != "" & descriptions != ""
    codes <- codes[valid_idx]
    descriptions <- descriptions[valid_idx]
    
    if (length(codes) == 0) {
      warning("No valid code-description pairs found in:\n", feature)
    }
    
    parsed_list[[header]] <- data.table(codes, descriptions)
  }
  
  return(parsed_list)
}

