#' Parse Text and Convert to a Data Table
#'
#' @param text Character string containing text to parse.
#' @param reference_table A named list of data.tables generated by \code{\link{parse_features}}.
#' @param label A character string to label the parsed features.
#' @param drop.na Logical. If TRUE, columns with all NA will be dropped.
#' @param speculation Logical. If TRUE, attempts to extract speculation values.
#' @param debug Logical. If TRUE, prints debug information.
#'
#' @details
#' This function takes a block of text and attempts to infer feature values from a 
#' given reference table. It matches features and values based on simple pattern 
#' matching. It can also extract "speculation" values if present.
#'
#' @return A data.table with parsed features (and speculation if applicable).
#'
#' @export
parse_text_to_datatable <- function(
    text, 
    reference_table, 
    label, 
    drop.na = FALSE, 
    speculation = TRUE,
    debug = FALSE
) {
  if (!is.character(text) || length(text) != 1) {
    stop("`text` must be a single character string.")
  }
  if (!is.list(reference_table) || length(reference_table) == 0) {
    stop("`reference_table` must be a non-empty named list (as returned by `parse_features`).")
  }
  if (!is.character(label) || length(label) != 1) {
    stop("`label` must be a single character string.")
  }
  
  features_object <- data.table()
  
  # Clean up text
  text <- gsub("\\*", "", text)
  
  # Remove lines containing "explanation" to reduce contradictory content
  lines <- unlist(strsplit(text, split = "\n"))
  if (any(grepl("explanation", tolower(lines)))) {
    lines <- lines[!grepl("explanation", tolower(lines))]
    text <- paste(lines, collapse = "\n")
  }
  
  if (debug) {
    cat("Debug: Processed text:\n", text, "\n")
  }
  
  # For each feature in reference_table, try to match a symbol or a value
  for (f in names(reference_table)) {
    values_choice <- character(0)
    symbols_choice <- character(0)
    
    # Check symbols (first column)
    sym_set <- unlist(reference_table[[f]][[1]])
    # Check descriptions (second column)
    val_set <- unlist(reference_table[[f]][[2]])
    
    # Match symbols
    for (s in sym_set) {
      if (grepl(s, text)) {
        symbols_choice <- c(symbols_choice, val_set[match(s, sym_set)])
      }
    }
    
    # Match values
    for (v in val_set) {
      if (grepl(v, text)) {
        values_choice <- c(values_choice, v)
      }
    }
    
    if (debug) {
      cat("\nFeature:", f, 
          "\nSymbols matched:", symbols_choice, 
          "\nValues matched:", values_choice, "\n")
    }
    
    # Combine potential matches
    combined_matches <- unique(c(values_choice, symbols_choice))
    if (length(combined_matches) == 0) {
      combined_matches <- NA
    } else if (length(combined_matches) > 1) {
      # Multiple matches found - this might indicate ambiguity
      # Choose one at random to proceed, but issue a warning
      warning("Multiple matches found for feature '", f, "' under label '", label, 
              "'. Choosing one at random: ", paste(combined_matches, collapse = ", "))
      combined_matches <- sample(combined_matches, 1)
    }
    
    inferred_value <- combined_matches
    if (debug) {
      cat("\nInferred value for feature", f, ":", inferred_value, "\n")
    }
    
    # Store choice in features_object
    features_object$temp <- inferred_value
    names(features_object)[names(features_object) == "temp"] <- paste0("gpt_", label, "_", f)
  }
  
  # Extract speculation if requested
  if (speculation) {
    feature_blocks <- strsplit(text, "\n\n")[[1]]
    for (f in names(reference_table)) {
      block <- character(0)
      if (any(grepl(f, feature_blocks))) {
        block <- grep(f, feature_blocks, value = TRUE)
      } else {
        # Try matching by common substring + digits
        f_star <- paste0(longest_common_substring(unlist(reference_table[[f]][1])), "[0-9]{1,2}")
        if (any(grepl(f_star, feature_blocks))) {
          block <- grep(f_star, feature_blocks, value = TRUE)
        }
      }
      
      speculation_val <- as.numeric(sub(".*[sS]peculat(ion|ive):?\\s*([0-9]+).*", "\\2", block))
      
      if (length(speculation_val) == 0 || all(is.na(speculation_val))) {
        speculation_val <- NA
        warning("** Missing speculation value for feature '", f, "' under label '", label, "' **")
      } else {
        # If multiple speculation values, take the maximum
        speculation_val <- max(as.numeric(as.character(unlist(speculation_val))), na.rm = TRUE)
      }
      
      features_object$temp <- speculation_val
      names(features_object)[names(features_object) == "temp"] <- paste0("gpt_speculation_", label, "_", f)
    }
  }
  
  if (drop.na) {
    nona_cols <- which(!is.na(unlist(features_object)))
    features_object <- features_object[, ..nona_cols]
  }
  
  return(features_object)
}

