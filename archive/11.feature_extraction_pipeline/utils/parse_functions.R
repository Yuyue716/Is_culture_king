#' Find Longest Common Substring Among Multiple Strings
#'
#' @param strings A character vector.
#'
#' @details
#' This function finds the longest common substring shared by all strings in the input.
#' If any string has no commonality, it returns an empty string.
#'
#' @return A character string representing the longest common substring.
#' 
#' @examples
#' longest_common_substring(c("catapult", "catamaran", "catastrophe"))
#' # Returns "cata"
#'
#' @export
longest_common_substring <- function(strings) {
  if (!is.character(strings)) {
    stop("`strings` must be a character vector.")
  }
  if (length(strings) == 0) return("")
  
  # Helper for LCS of two strings
  lcs_two_strings <- function(str1, str2) {
    m <- nchar(str1)
    n <- nchar(str2)
    lengths <- matrix(0, m + 1, n + 1)
    longest_length <- 0
    ending_index_str1 <- 0
    
    for (i in seq_len(m)) {
      for (j in seq_len(n)) {
        if (substr(str1, i, i) == substr(str2, j, j)) {
          lengths[i + 1, j + 1] <- lengths[i, j] + 1
          if (lengths[i + 1, j + 1] > longest_length) {
            longest_length <- lengths[i + 1, j + 1]
            ending_index_str1 <- i + 1
          }
        }
      }
    }
    
    if (longest_length > 0) {
      substring(str1, ending_index_str1 - longest_length, ending_index_str1 - 1)
    } else {
      ""
    }
  }
  
  common_substring <- strings[1]
  for (str in strings[-1]) {
    common_substring <- lcs_two_strings(common_substring, str)
    if (common_substring == "") break
  }
  
  return(common_substring)
}

